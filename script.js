const $ = (selector, root=document) => root.querySelector(selector);
const $$ = (selector, root=document) => [...root.querySelectorAll(selector)];

function setLanguage(lang){
  const dict = translations[lang] || translations.es;
  $$("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });
  $$(".lang-btn").forEach(btn => btn.classList.toggle("active", btn.dataset.lang === lang));
  document.documentElement.lang = lang;
  localStorage.setItem("dfd-language", lang);
}

function applyAutomaticEyeMode(){
  const hour = new Date().getHours();
  const isNight = hour >= 19 || hour < 7;
  document.body.classList.toggle("night-mode", isNight);
  document.documentElement.style.colorScheme = isNight ? "dark" : "light";
}

function initThemeToggle(){
  const btn = $("#themeToggle");
  btn.addEventListener("click", () => {
    const isNight = document.body.classList.toggle("night-mode");
    document.documentElement.style.colorScheme = isNight ? "dark" : "light";
    localStorage.setItem("dfd-manual-theme", isNight ? "night" : "day");
    showToast(isNight ? "Modo descanso activado" : "Modo claro activado");
  });
  const saved = localStorage.getItem("dfd-manual-theme");
  if(saved) {
    document.body.classList.toggle("night-mode", saved === "night");
    document.documentElement.style.colorScheme = saved === "night" ? "dark" : "light";
  } else {
    applyAutomaticEyeMode();
  }
}

function initMenu(){
  const toggle = $("#menuToggle");
  const nav = $("#mainNav");
  toggle.addEventListener("click", () => nav.classList.toggle("open"));
  $$("#mainNav a").forEach(link => link.addEventListener("click", () => nav.classList.remove("open")));
}

function initReveal(){
  const items = $$(".reveal");
  if(!("IntersectionObserver" in window)){
    items.forEach(el => el.classList.add("visible"));
    return;
  }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if(entry.isIntersecting){
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, {threshold:.12});
  items.forEach(el => observer.observe(el));
}

function initBackTop(){
  const btn = $("#backTop");
  window.addEventListener("scroll", () => btn.classList.toggle("visible", window.scrollY > 650), {passive:true});
  btn.addEventListener("click", () => window.scrollTo({top:0,behavior:"smooth"}));
}

function showToast(message){
  const toast = $("#toast");
  toast.textContent = message;
  toast.classList.add("show");
  clearTimeout(showToast.timer);
  showToast.timer = setTimeout(() => toast.classList.remove("show"), 1800);
}

document.addEventListener("DOMContentLoaded", () => {
  $("#year").textContent = new Date().getFullYear();

  const savedLanguage = localStorage.getItem("dfd-language") || "es";
  setLanguage(savedLanguage);

  $$(".lang-btn").forEach(btn => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });

  initThemeToggle();
  initMenu();
  initReveal();
  initBackTop();

  // Re-evaluate automatic eye mode hourly when no manual theme was chosen.
  setInterval(() => {
    if(!localStorage.getItem("dfd-manual-theme")) applyAutomaticEyeMode();
  }, 60 * 60 * 1000);
});
